"""Reproduces every number and the figure in the article from the released traces in data/.

Usage (from the repo root): python analysis/results.py
Writes analysis/results.md and figures/budget_curve.png. Grading uses math-verify; takes ~30 min on a laptop.
"""
import collections, glob, gzip, json, os, sys
import pandas as pd
from math_verify import parse, verify

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from loopdiag import last_boxed, loop_onset, split_final

BUDGETS = [512, 1024, 2048, 3072, 4096, 6144, 8192]
MIT = 48.1  # Weight-Space Programming, edited Qwen3.5-0.8B, 32k tokens, avg@4


def ok(pred, gold):
    if pred is None:
        return False
    try:
        return bool(verify(parse("$" + gold + "$"), parse("$" + pred + "$")))
    except Exception:
        return False


def load(path):
    return [json.loads(l) for l in gzip.open(path, "rt")]


def run_stats(gen_path, ckpt_path):
    """Natural accuracy, truncation, loop rate, and accuracy with the answer forced at each budget."""
    gen = load(gen_path)
    gold = {r["unique_id"]: r["answer"] for r in gen}
    row = dict(
        n=len(gen),
        natural=100 * sum(ok(last_boxed(split_final(r["text"], True)[1]), r["answer"]) for r in gen) / len(gen),
        truncated=100 * sum(r["finish_reason"] == "length" for r in gen) / len(gen),
        looping=100 * sum(loop_onset(r["token_ids"]) is not None for r in gen) / len(gen),
        instr_tokens=gen[0]["instruction_tokens"],
    )
    ck = pd.DataFrame(load(ckpt_path))
    ck["c"] = [ok(p, gold[u]) for p, u in zip(ck.pred, ck.unique_id)]
    for b in BUDGETS:  # answer forced at the last checkpoint <= b (or at the trace's own end if shorter)
        last = ck[ck.t <= b].sort_values("t").groupby("unique_id").c.last()
        row[f"@{b}"] = 100 * last.reindex(list(gold)).fillna(False).mean()
    row["oracle"] = 100 * ck.groupby("unique_id").c.any().mean()
    return row, ck, gold


def vote_stats(cks, gold, b):
    """Majority vote over the forced answers of all checkpoints <= b (pooled over runs)."""
    votes = collections.defaultdict(list)
    for ck in cks:
        for u, t, p in zip(ck.unique_id, ck.t, ck.pred):
            if t <= b and isinstance(p, str):
                votes[u].append(p.strip())
    pick = {u: collections.Counter(v).most_common(1)[0][0] for u, v in votes.items()}
    return 100 * sum(ok(pick.get(u), g) for u, g in gold.items()) / len(gold)


def main():
    out = ["# Results (generated by analysis/results.py)\n"]
    rows, cks = {}, {}
    for d in ["full500_seed0", "full500_seed1", "full500_terse1"]:
        name = "terse1" if "terse1" in d else "base"
        rows[d], cks[d], gold = run_stats(f"{ROOT}/data/{d}/gen_{name}.jsonl.gz", f"{ROOT}/data/{d}/ckpt_{name}.jsonl.gz")
        print(d, {k: round(v, 1) for k, v in rows[d].items()}, flush=True)
    t = pd.DataFrame(rows).T.round(1)
    out += ["## Full MATH-500 (500 problems, 1 sample per run, 8k budget)\n", t.to_markdown(), ""]
    out += [f"Majority vote over checkpoints <= 8192 (seed 0): {vote_stats([cks['full500_seed0']], gold, 8192):.1f}",
            f"Majority vote pooled over seeds 0+1: {vote_stats([cks['full500_seed0'], cks['full500_seed1']], gold, 8192):.1f}", ""]

    sub = {}
    for g in sorted(glob.glob(f"{ROOT}/data/subset100_prompts/gen_*.jsonl.gz")):
        v = os.path.basename(g)[4:-9]
        sub[v], _, _ = run_stats(g, g.replace("gen_", "ckpt_"))
        print(v, round(sub[v]["natural"], 1), flush=True)
    out += ["## Prompt and nudge variants (100-problem subset, every 5th problem)\n",
            pd.DataFrame(sub).T.round(1).sort_values("natural", ascending=False).to_markdown(), ""]
    open(f"{ROOT}/analysis/results.md", "w").write("\n".join(out))

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(6.4, 4))
    for d, lab, c in [("full500_seed0", "base model, seed 0", "#2563eb"), ("full500_seed1", "base model, seed 1", "#60a5fa")]:
        ax.plot(BUDGETS, [rows[d][f"@{b}"] for b in BUDGETS], marker="o", color=c, label=f"{lab}: answer forced at budget")
    ax.axhline(rows["full500_seed0"]["natural"], color="#9ca3af", ls=":", label="base model, no forcing (8k)")
    ax.axhline(MIT, color="#dc2626", ls="--", label="MIT weight-edited model (32k, avg@4)")
    ax.set_xscale("log", base=2)
    ax.set_xticks(BUDGETS, [f"{b // 1024}k" if b >= 1024 else "512" for b in BUDGETS])
    ax.set_xlabel("thinking budget (tokens)")
    ax.set_ylabel("MATH-500 accuracy (%)")
    ax.set_ylim(0, 55)
    ax.set_title("Qwen3.5-0.8B: stop the loop, keep the weights")
    ax.legend(fontsize=8, loc="lower right")
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(f"{ROOT}/figures/budget_curve.png", dpi=160)


if __name__ == "__main__":
    main()
